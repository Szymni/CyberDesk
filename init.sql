CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, username VARCHAR(50) UNIQUE NOT NULL, password TEXT NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (LOWER(username));
CREATE TABLE IF NOT EXISTS reports (
 id SERIAL PRIMARY KEY, author VARCHAR(50) NOT NULL, title VARCHAR(150) NOT NULL, description TEXT NOT NULL,
 severity VARCHAR(20) NOT NULL CHECK (severity IN ('Niska','Średnia','Wysoka','Krytyczna')),
 approved BOOLEAN NOT NULL DEFAULT FALSE,
 status VARCHAR(30) NOT NULL DEFAULT 'Nowe' CHECK (status IN ('Nowe','W trakcie analizy','Naprawione')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reports_author ON reports (author);
CREATE INDEX IF NOT EXISTS reports_approved ON reports (approved);
CREATE TABLE IF NOT EXISTS comments (
 id SERIAL PRIMARY KEY, report_id INTEGER NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
 author VARCHAR(50) NOT NULL, content TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS comments_report ON comments (report_id);
CREATE TABLE IF NOT EXISTS login_attempts (
 key VARCHAR(64) PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0,
 last_attempt BIGINT NOT NULL, blocked_until BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS audit_events (
 id SERIAL PRIMARY KEY, actor VARCHAR(50) NOT NULL, event VARCHAR(100) NOT NULL,
 report_id INTEGER, detail TEXT NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
